package sample;

public class SimpleLiterals {
	public static void main(String[] args) {
		//Whole number 
		
		int age =25;
		long stars= 9999999L;
		
		//Decimal
		
		double price =19.99;
		float tax = 0.05F;
		
		//others
		
		boolean isOpen=true;
		char grade = 'A';
		
		System.out.println(age+","+stars+";"+price+";"+tax+";"+isOpen+";"+grade);
	}

}
